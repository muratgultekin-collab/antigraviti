-- Mikro veritabanı seçili olmalı (USE MikroDB_V16_xxx)

-- 2a) Aday tablolar (isim desenine göre)
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME IN ('STOKLAR','STOK_HAREKETLERI','STOK_ANA_GRUPLARI','STOK_ALT_GRUPLARI','STOK_KATEGORILERI',
                     'DOVIZ_KURLARI','DOVIZLER','CARI_HESAPLAR')
   OR TABLE_NAME LIKE '%RECETE%'
   OR TABLE_NAME LIKE '%DOVIZ%'
   OR TABLE_NAME LIKE '%KUR%'
   OR TABLE_NAME LIKE 'STOK_%GRUP%'
   OR TABLE_NAME LIKE 'STOK_KATEGOR%'
ORDER BY TABLE_TYPE, TABLE_NAME;

-- 2b) Bu tabloların kolonları
SELECT c.TABLE_NAME, c.ORDINAL_POSITION, c.COLUMN_NAME, c.DATA_TYPE,
       c.CHARACTER_MAXIMUM_LENGTH, c.NUMERIC_PRECISION, c.NUMERIC_SCALE, c.IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS c
JOIN INFORMATION_SCHEMA.TABLES t ON t.TABLE_NAME = c.TABLE_NAME AND t.TABLE_SCHEMA = c.TABLE_SCHEMA
WHERE t.TABLE_TYPE = 'BASE TABLE'
  AND (c.TABLE_NAME IN ('STOKLAR','STOK_HAREKETLERI','STOK_ANA_GRUPLARI','STOK_ALT_GRUPLARI','STOK_KATEGORILERI',
                        'DOVIZ_KURLARI','DOVIZLER','CARI_HESAPLAR')
       OR c.TABLE_NAME LIKE '%RECETE%')
ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION;

-- 2c) Beklenen kritik kolonların var/yok kontrolü
;WITH beklenen(tablo, kolon) AS (
  SELECT 'STOKLAR','sto_kod' UNION ALL SELECT 'STOKLAR','sto_isim' UNION ALL
  SELECT 'STOKLAR','sto_anagrup_kod' UNION ALL SELECT 'STOKLAR','sto_altgrup_kod' UNION ALL
  SELECT 'STOKLAR','sto_kategori_kod' UNION ALL SELECT 'STOKLAR','sto_birim1_ad' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_tarih' UNION ALL SELECT 'STOK_HAREKETLERI','sth_stok_kod' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_miktar' UNION ALL SELECT 'STOK_HAREKETLERI','sth_tutar' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_tip' UNION ALL SELECT 'STOK_HAREKETLERI','sth_cins' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_evraktip' UNION ALL SELECT 'STOK_HAREKETLERI','sth_normal_iade' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_har_doviz_cinsi' UNION ALL SELECT 'STOK_HAREKETLERI','sth_har_doviz_kuru' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_iskonto1' UNION ALL SELECT 'STOK_HAREKETLERI','sth_fat_uid' UNION ALL
  SELECT 'STOK_HAREKETLERI','sth_cari_kodu' UNION ALL SELECT 'STOK_HAREKETLERI','sth_evrakno_seri'
)
SELECT b.tablo, b.kolon,
       CASE WHEN c.COLUMN_NAME IS NULL THEN 'YOK' ELSE 'VAR' END AS durum, c.DATA_TYPE
FROM beklenen b
LEFT JOIN INFORMATION_SCHEMA.COLUMNS c ON c.TABLE_NAME = b.tablo AND c.COLUMN_NAME = b.kolon
ORDER BY b.tablo, b.kolon;
